// Copies drizzle/*.sql into a TypeScript module so migrations ship inside the
// server bundle (no filesystem access needed on Vercel). Run after drizzle-kit generate.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const dir = path.resolve(import.meta.dirname, '..', 'drizzle')
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
const migrations = files.map((file) => ({
  tag: file.replace(/\.sql$/, ''),
  statements: readFileSync(path.join(dir, file), 'utf8')
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter(Boolean),
}))
const out = `// Generated by scripts/embed-migrations.mjs — do not edit.\nexport const migrations: { tag: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)}\n`
writeFileSync(path.resolve(import.meta.dirname, '..', 'src', 'server', 'db', 'migrations.ts'), out)
console.log(`Embedded ${migrations.length} migration(s).`)
